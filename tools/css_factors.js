function top_level_params(parstr) {
    parstr = parstr.trim()
    let n = parstr.length
    let lastp = ""
    let params = []
    let depth = 0
    for ( let i = 0; i < n; i++ ) {
        let c = parstr[i]
        if ( c === ',' && (depth <= 0) ) {
            params.push(lastp)
            lastp = ""
        } else {
            lastp += c
        }
        if ( c === '(' ) { depth++ }
        if ( c === ')' ) { depth-- }
    }
    params.push(lastp)
    return params
}


