function normalize_css_def_str(defstr) {
    defstr = defstr.replaceAll(/\s\s+/g,' ')
    defstr = defstr.replaceAll('\n','')
    return defstr
}


/**
 * 
 * @param {Array} salient 
 * @returns {Array}
 */
function normalize_css_def_str_array(cssarray) {
    for ( let i = 0; i < cssarray.length; i++ ) {
        let line = cssarray[i]
        line = normalize_css_def_str(line)
        line = line.replaceAll('))',')')
        if ( line[0] != '@') {
            line = line.replace('}}','}')
        }
        line = line.replaceAll(/;\s+\}/g,';}')
        cssarray[i] = line
    }
    return cssarray
}

function normalize_css_def_str_all(salient) {
    for ( let ky in salient ) {
        let css_array = salient[ky]
        salient[ky] = normalize_css_def_str_array(css_array)
    }
    return salient
}

